#!/usr/bin/env python3
"""Recover complete RadiaCode VS_DATA_BUF records from reconstructed ATT CSV.

Input is generated by the offline BLE/L2CAP reassembler. Outputs raw values:
unit conversion is intentionally not applied without independent validation.
"""
import argparse
import csv
import struct
from pathlib import Path

KNOWN = {0x0005, 0x0007, 0x000A, 0x000B, 0x0101, 0x0807, 0x0824,
         0x0825, 0x0826, 0x0827, 0x082A, 0x082B, 0x0A04}
SIZES = {(0,0):15,(0,1):8,(0,2):16,(0,3):14,(0,4):16,
         (0,5):16,(0,6):6,(0,7):4,(0,8):6,(0,9):6}

def records(data):
    p = 0
    out = []
    while p + 7 <= len(data):
        seq, eid, gid, ts = struct.unpack_from('<BBBi', data, p)
        size = SIZES.get((eid, gid))
        if size is None or p + 7 + size > len(data):
            break
        payload = data[p + 7:p + 7 + size]
        p += 7 + size
        if (eid, gid) == (0, 0):
            cps, rate, _, _, _, _ = struct.unpack('<ffHHHB', payload)
            out.append(('RealTimeData', seq, ts, cps, rate, None, None))
        elif (eid, gid) == (0, 3):
            duration, dose, _, _, _ = struct.unpack('<IfHHH', payload)
            out.append(('RareData', seq, ts, None, None, duration, dose))
        elif (eid, gid) == (0, 1):
            cps, rate = struct.unpack('<ff', payload)
            out.append(('RawData', seq, ts, cps, rate, None, None))
    return out, p

def main():
    pa = argparse.ArgumentParser(description=__doc__)
    pa.add_argument('att_csv', type=Path)
    pa.add_argument('--output', type=Path, default=Path('radiacode_recovered_measurements.csv'))
    args = pa.parse_args()
    with args.att_csv.open(newline='', encoding='utf-8') as f:
        rows = list(csv.DictReader(f))
    stream = b''.join(bytes.fromhex(r['value_hex']) for r in rows
                      if r['opcode'] == '0x1B' and r['handle'] == '0x0010')
    pos = 0
    frames = 0
    found = []
    while pos + 8 <= len(stream):
        length = struct.unpack_from('<I', stream, pos)[0]
        cmd, flags, seq = struct.unpack_from('<HBB', stream, pos + 4)
        if not (4 <= length <= 20000 and cmd in KNOWN and flags == 0 and seq == 0x80):
            pos += 1
            continue
        end = pos + 4 + length
        if end > len(stream):
            pos += 1
            continue
        payload = stream[pos + 8:end]
        if cmd == 0x0826 and len(payload) >= 8:
            ret, data_size = struct.unpack_from('<II', payload)
            if data_size == len(payload) - 8 and ret == 1:
                data = payload[8:]
                parsed, consumed = records(data)
                if consumed == len(data) and parsed:
                    for kind, record_seq, ts, cps, rate, duration, dose in parsed:
                        found.append(dict(frame_offset=pos, record_type=kind,
                            record_seq=record_seq, timestamp_offset_10ms=ts,
                            count_rate_raw=cps, dose_rate_raw=rate,
                            duration_s=duration, dose_raw=dose))
        frames += 1
        pos = end
    with args.output.open('w', newline='', encoding='utf-8') as f:
        fields = ['frame_offset','record_type','record_seq','timestamp_offset_10ms',
                  'count_rate_raw','dose_rate_raw','duration_s','dose_raw']
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(found)
    from collections import Counter
    print('Replies:', frames, 'records:', dict(Counter(x['record_type'] for x in found)))
    print('Saved:', args.output)

if __name__ == '__main__':
    main()
